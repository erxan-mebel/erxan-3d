  def self.pt(x, y, z) Geom::Point3d.new(x.mm, y.mm, z.mm) end

  def self.box(ents, name, x0, y0, z0, x1, y1, z1, mat, tag)
    g = ents.add_group
    g.name = name
    f = g.entities.add_face(pt(x0, y0, z0), pt(x1, y0, z0), pt(x1, y1, z0), pt(x0, y1, z0))
    f.reverse! if f.normal.z < 0
    f.pushpull((z1 - z0).mm)
    g.material = mat
    g.layer = tag
    g
  end

  def self.rod(ents, name, x0, x1, yc, zc, r, mat, tag)
    g = ents.add_group
    g.name = name
    edges = g.entities.add_circle(pt(x0, yc, zc), Geom::Vector3d.new(1, 0, 0), r.mm, 24)
    f = g.entities.add_face(edges)
    f.reverse! if f.normal.x < 0
    f.pushpull((x1 - x0).mm)
    g.material = mat
    g.layer = tag
    g
  end

